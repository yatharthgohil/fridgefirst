import { z } from "zod";
import { positiveQuantitySchema, quantityDeltaSchema, quantitySchema, timestampSchema, unitSchema } from "./common";

// Existing UI models carry string units. Validate tokens without narrowing that public type.
const inventoryUnitSchema = unitSchema.transform((unit): string => unit);

export const INVENTORY_ENDPOINTS = {
  /** POST InventoryAdjustmentRequest -> InventoryAdjustmentResponse */
  adjustments: "/api/inventory/adjustments",
  /** GET ?limit=n -> InventoryHistoryResponse (newest first) */
  history: "/api/inventory/history",
} as const;

/** Every operation that can appear in inventory history. */
export const inventoryOperationSchema = z.enum([
  "add",
  "edit",
  "delete",
  "consume",
  "discard",
  "recipe_deduction",
]);
export type InventoryOperation = z.infer<typeof inventoryOperationSchema>;

/** Operations a user can perform directly from the consume/discard controls. */
export const adjustmentOperationSchema = z.enum(["consume", "discard"]);
export type AdjustmentOperation = z.infer<typeof adjustmentOperationSchema>;

export const inventoryAdjustmentRequestSchema = z.strictObject({
  /**
   * Idempotency key generated by the client for one intended deduction.
   * Retries of the same intent reuse it; the server must apply a given
   * requestId at most once and return the original result on replay.
   */
  requestId: z.string().min(8).max(128),
  itemId: z.string().min(1),
  operation: adjustmentOperationSchema,
  /** Amount to remove, expressed in the item's current unit. */
  amount: positiveQuantitySchema,
  /** Must equal the item's stored unit; units are never converted silently. */
  unit: inventoryUnitSchema,
  /**
   * The quantity the user saw when confirming. If the stored quantity differs,
   * the server rejects with `conflict` so the user can review the latest value.
   */
  expectedQuantity: quantitySchema,
});
export type InventoryAdjustmentRequest = z.infer<typeof inventoryAdjustmentRequestSchema>;

export const itemQuantitySchema = z.object({
  id: z.string(),
  quantity: quantitySchema,
  unit: inventoryUnitSchema,
});
export type ItemQuantity = z.infer<typeof itemQuantitySchema>;

export const inventoryHistoryEntrySchema = z.object({
  id: z.string(),
  /** Null when the item has since been deleted and its row is gone. */
  itemId: z.string().nullable(),
  /** Name captured at the time of the change, so deleted items stay readable. */
  itemName: z.string(),
  operation: inventoryOperationSchema,
  /** Signed change (negative for removals); null when quantity did not change. */
  quantityDelta: quantityDeltaSchema.nullable(),
  unit: inventoryUnitSchema.nullable(),
  /** ISO-8601 timestamp. */
  occurredAt: timestampSchema,
});
export type InventoryHistoryEntry = z.infer<typeof inventoryHistoryEntrySchema>;

export const inventoryAdjustmentResponseSchema = z.object({
  item: itemQuantitySchema,
  entry: inventoryHistoryEntrySchema,
  /** True when this requestId had already been applied and nothing changed now. */
  replayed: z.boolean().default(false),
});
export type InventoryAdjustmentResponse = z.infer<typeof inventoryAdjustmentResponseSchema>;

export const inventoryHistoryResponseSchema = z.object({
  entries: z.array(inventoryHistoryEntrySchema),
});
export type InventoryHistoryResponse = z.infer<typeof inventoryHistoryResponseSchema>;

/**
 * Error codes. HTTP mapping: 400/422 validation, 401 unauthorized,
 * 404 not_found, 409 conflict, 5xx server. `network` is client-side only.
 */
export const inventoryErrorCodeSchema = z.enum([
  "validation",
  "conflict",
  "not_found",
  "unauthorized",
  "server",
]);
export type InventoryErrorCode = z.infer<typeof inventoryErrorCodeSchema> | "network";

export const inventoryErrorResponseSchema = z.object({
  error: z.object({
    code: inventoryErrorCodeSchema,
    message: z.string(),
    /** For `conflict`: the item's latest stored quantity. */
    current: itemQuantitySchema.optional(),
  }),
});
export type InventoryErrorResponse = z.infer<typeof inventoryErrorResponseSchema>;
